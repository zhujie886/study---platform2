export const fortunePool: Fortune[] = (() => {
  const out: Fortune[] = [];
  Object.entries(tierTemplates).forEach(([tier, templates]) => {
    for (let i = 0; i < 25; i++) {
      const base = templates[i % templates.length];
      out.push({ tier, text: `${base} · 第${i + 1}签` });
    }
  });
  return out;
})();

